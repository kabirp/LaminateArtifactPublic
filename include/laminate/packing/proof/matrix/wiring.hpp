#ifndef LAMINATE_PACKING_PROOF_WIRING_HPP
#define LAMINATE_PACKING_PROOF_WIRING_HPP

/// @file wiring.hpp
/// @brief Compact external-memory row-bound matrix for packing Spartan.

#include "laminate/packing/proof/matrix/oracle.hpp"
#include "laminate/storage/native_field_artifact.hpp"

#include <cstddef>
#include <cstdint>
#include <filesystem>
#include <memory>
#include <span>
#include <string_view>

namespace laminate::packing {

inline constexpr std::string_view
    kProofOfPackingWiringPublicColumns = "public-columns";
inline constexpr std::string_view
    kProofOfPackingWiringWitnessColumns = "witness-columns";

/// Caller-owned destination and hard limits for the compact row-bound matrix.
/// `max_working_field_bytes` covers every dynamically retained Fq/Fq2 table,
/// output block, and tensor-column cache used by the writer.
struct ProofOfPackingWiringArtifactOptions {
    std::filesystem::path directory;
    storage::NativeFieldArtifactOptions storage_limits;
    /// Complete bytes allowed while the validated tensor source and the
    /// completed compact matrix coexist. This checkpoint owns no scratch.
    std::uint64_t max_live_storage_bytes = 0;
    std::uint64_t max_working_field_bytes = 0;
    std::size_t block_elements = 0;
};

struct ProofOfPackingWiringArtifactPlan {
    std::uint64_t physical_bytes = 0;
    std::uint64_t source_artifact_physical_bytes = 0;
    std::uint64_t peak_live_storage_bytes = 0;
    std::uint64_t row_prefix_equality_table_elements = 0;
    std::uint64_t coordinate_equality_table_elements = 0;
    std::uint64_t row_family_weight_elements = 0;
    std::uint64_t tensor_columns = 0;
    std::uint64_t retained_working_field_bytes = 0;
    std::uint64_t minimum_working_field_bytes = 0;
    std::size_t effective_block_elements = 0;
    std::uint64_t tensor_cache_elements = 0;
    std::uint64_t peak_working_field_bytes = 0;

    bool operator==(
        const ProofOfPackingWiringArtifactPlan &) const = default;
};

struct ProofOfPackingWiringIoReport {
    std::uint64_t payload_bytes = 0;
    std::uint64_t read_operations = 0;
    std::uint64_t seek_operations = 0;

    bool operator==(const ProofOfPackingWiringIoReport &) const = default;
};

/// Predict the tensor-column cache traffic generated by the canonical
/// witness-column traversal. This is a value-free planning calculation: it
/// walks only the setup-selected commitment-witness segment geometry and
/// owner addresses, and never opens an artifact or allocates a tensor table.
/// Counts use the same logical block reads and explicit seeks reported by the
/// writer.
ProofOfPackingWiringIoReport
estimate_proof_of_packing_wiring_tensor_io(
    const OuterRelationPlan &plan,
    const ProofOfPackingR1csLayout &layout,
    std::span<const PackingTensorMapping> mappings,
    std::size_t block_elements);

/// Exact storage, I/O, and controlled-field-memory ledger for one artifact.
struct ProofOfPackingWiringArtifactReport {
    std::uint64_t public_column_elements = 0;
    std::uint64_t witness_column_elements = 0;
    std::uint64_t logical_padded_column_elements = 0;
    std::uint64_t virtual_zero_column_elements = 0;
    std::uint64_t matrix_payload_bytes = 0;
    std::uint64_t physical_bytes = 0;
    std::uint64_t source_artifact_physical_bytes = 0;
    std::uint64_t source_artifact_validation_bytes = 0;
    std::uint64_t output_artifact_validation_bytes = 0;
    std::uint64_t peak_live_storage_bytes = 0;
    std::uint64_t sequential_output_payload_bytes = 0;
    std::uint64_t sequential_output_operations = 0;
    ProofOfPackingWiringIoReport factored_tensor_io;
    std::uint64_t row_prefix_equality_table_elements = 0;
    std::uint64_t coordinate_equality_table_elements = 0;
    std::uint64_t row_family_weight_elements = 0;
    std::uint64_t tensor_cache_elements = 0;
    std::size_t effective_block_elements = 0;
    std::uint64_t peak_working_field_bytes = 0;

    bool operator==(const ProofOfPackingWiringArtifactReport &) const =
        default;
};

struct ProofOfPackingWiringArtifact {
    std::shared_ptr<const storage::NativeFieldArtifact> artifact;
    ProofOfPackingWiringArtifactReport report;
};

/// Exact Fq2 payload bytes for the two physical prefixes. Spartan's public
/// and witness padding is deliberately absent from this count.
std::uint64_t proof_of_packing_wiring_matrix_payload_bytes(
    const spartan::R1csMetadata &circuit_metadata);

/// Exact completed row-bound Wiring artifact size.
std::uint64_t proof_of_packing_wiring_matrix_artifact_physical_bytes(
    const spartan::R1csMetadata &circuit_metadata);

ProofOfPackingWiringArtifactPlan
plan_proof_of_packing_wiring_matrix_artifact(
    const OuterRelationPlan &plan,
    const ProofOfPackingR1csLayout &layout,
    const spartan::R1csMetadata &circuit_metadata,
    const spartan::FactoredMatrixProverKey &factored_preprocessing,
    std::uint64_t max_working_field_bytes,
    std::size_t requested_block_elements);

/// Bind the compact matrix to the exact relation, committed factored source,
/// row point, batching challenge, and physical prefix lengths.
Digest proof_of_packing_wiring_matrix_artifact_identity(
    const OuterRelationPlan &plan,
    const ProofOfPackingR1csLayout &layout,
    const spartan::R1csMetadata &circuit_metadata,
    const spartan::FactoredMatrixProverKey &factored_preprocessing,
    std::span<const Fq2> row_point, const Fq2 &gamma);

/// Reopen the canonical `public-columns` and `witness-columns` Fq2 arrays.
std::shared_ptr<const storage::NativeFieldArtifact>
open_proof_of_packing_wiring_matrix_artifact(
    const std::filesystem::path &directory,
    const OuterRelationPlan &plan,
    const ProofOfPackingR1csLayout &layout,
    const spartan::R1csMetadata &circuit_metadata,
    const spartan::FactoredMatrixProverKey &factored_preprocessing,
    std::span<const Fq2> row_point, const Fq2 &gamma);

/// Read an arbitrary range of the logical padded Wiring table. Missing public
/// and witness tails are synthesized as zero; only live prefixes cause I/O.
void read_proof_of_packing_wiring_matrix_range(
    const storage::NativeFieldArtifact &artifact,
    const spartan::R1csMetadata &circuit_metadata,
    std::uint64_t begin, std::span<Fq2> output);

/// Write M(r_x,.) for M=A+gamma B+gamma^2 C directly in conventional-column
/// order. The implementation does not expand A/B/C, call the dense wiring
/// evaluator, evaluate one full MLE per column, or materialize a tensor
/// operand. On failure it restores the destination to empty.
ProofOfPackingWiringArtifact
write_proof_of_packing_wiring_matrix_artifact(
    const OuterRelationPlan &plan,
    const ProofOfPackingR1csLayout &layout,
    const spartan::R1csMetadata &circuit_metadata,
    const spartan::FactoredMatrixProverKey &factored_preprocessing,
    std::span<const Fq2> row_point, const Fq2 &gamma,
    ProofOfPackingWiringArtifactOptions options);

/// Admission-only counterpart that consumes a factored tensor artifact
/// already integrity-checked and lifetime-bound by the enclosing suffix.
/// The generated Wiring artifact is still validated before publication.
ProofOfPackingWiringArtifact
write_proof_of_packing_wiring_matrix_artifact_admitted_source(
    const OuterRelationPlan &plan,
    const ProofOfPackingR1csLayout &layout,
    const spartan::R1csMetadata &circuit_metadata,
    const spartan::FactoredMatrixProverKey &factored_preprocessing,
    std::span<const Fq2> row_point, const Fq2 &gamma,
    ProofOfPackingWiringArtifactOptions options);

} // namespace laminate::packing

#endif // LAMINATE_PACKING_PROOF_WIRING_HPP
