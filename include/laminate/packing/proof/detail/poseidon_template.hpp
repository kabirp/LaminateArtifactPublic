#ifndef LAMINATE_PACKING_PROOF_DETAIL_POSEIDON_TEMPLATE_HPP
#define LAMINATE_PACKING_PROOF_DETAIL_POSEIDON_TEMPLATE_HPP

/// @file poseidon_template.hpp
/// @brief One public local Poseidon-permutation R1CS template.

#include "laminate/spartan/r1cs.hpp"
#include "laminate/crypto/poseidon.hpp"

#include <array>
#include <cstdint>
#include <vector>

namespace laminate::packing::detail {

/// Synthetic conventional columns used by `PoseidonPermutationR1csTemplate`:
/// constant column 0, then kPoseidonWidth prior-state columns, followed by
/// kPoseidonRate absorbed-input columns and the local auxiliary witnesses.
struct PoseidonPermutationR1csTemplate {
    std::vector<spartan::R1csEntry> a;
    std::vector<spartan::R1csEntry> b;
    std::vector<spartan::R1csEntry> c;
    std::array<std::uint64_t, kPoseidonWidth> final_auxiliary{};
    std::uint64_t rows = 0;
};

/// Return the exact local template generated by the production synthesizer.
/// The immutable result is initialized once and shared by matrix oracles.
const PoseidonPermutationR1csTemplate &
proof_of_packing_poseidon_permutation_template();

} // namespace laminate::packing::detail

#endif // LAMINATE_PACKING_PROOF_DETAIL_POSEIDON_TEMPLATE_HPP
